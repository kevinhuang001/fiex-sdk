//! HTTP convenience API. Core owns connections, redirects and authorization.
use crate::context::{rpc_to_io, ContextInner};
use base64::{engine::general_purpose::STANDARD, Engine};
use serde::{de::DeserializeOwned, Serialize};
use serde_json::json;
use std::{
    collections::BTreeMap,
    io::{self, Read},
    time::Duration,
};

const READ_LIMIT: usize = 64 * 1024 * 1024;

#[derive(Clone)]
pub struct HttpClient {
    context: ContextInner,
}

impl HttpClient {
    pub(crate) fn new(context: ContextInner) -> Self {
        Self { context }
    }

    pub fn request(&self, method: &str, url: &str) -> Request {
        Request {
            client: self.clone(),
            method: method.into(),
            url: url.into(),
            headers: BTreeMap::new(),
            body: Vec::new(),
            body_reader: None,
            timeout: Duration::from_secs(90),
            allow_invalid_certs: false,
        }
    }

    pub fn get(&self, url: &str) -> Request {
        self.request("GET", url)
    }

    pub fn post(&self, url: &str) -> Request {
        self.request("POST", url)
    }

    pub fn put(&self, url: &str) -> Request {
        self.request("PUT", url)
    }

    pub fn delete(&self, url: &str) -> Request {
        self.request("DELETE", url)
    }
}

pub struct Request {
    client: HttpClient,
    method: String,
    url: String,
    headers: BTreeMap<String, String>,
    body: Vec<u8>,
    body_reader: Option<crate::files::FileReader>,
    timeout: Duration,
    allow_invalid_certs: bool,
}

impl Request {
    pub fn header(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.headers.insert(name.into(), value.into());
        self
    }

    pub fn body(mut self, body: impl AsRef<[u8]>) -> Self {
        self.body_reader = None;
        self.body = body.as_ref().to_vec();
        self
    }

    /// Stream a Core-authorized file directly to HTTP, without buffering it
    /// in the plugin or copying its bytes through IPC. Consumes the reader.
    pub fn body_reader(mut self, reader: crate::files::FileReader) -> Self {
        self.body.clear();
        self.body_reader = Some(reader);
        self.timeout = self.timeout.max(Duration::from_secs(3600));
        self
    }

    pub fn json<T: Serialize>(mut self, value: &T) -> io::Result<Self> {
        self.body_reader = None;
        self.body = serde_json::to_vec(value).map_err(io::Error::other)?;
        self.headers
            .insert("content-type".into(), "application/json".into());
        Ok(self)
    }

    pub fn basic_auth(self, username: &str, password: &str) -> Self {
        self.header(
            "authorization",
            format!(
                "Basic {}",
                STANDARD.encode(format!("{username}:{password}"))
            ),
        )
    }

    pub fn bearer_auth(self, token: &str) -> Self {
        self.header("authorization", format!("Bearer {token}"))
    }

    pub fn timeout(mut self, timeout: Duration) -> Self {
        self.timeout = timeout;
        self
    }

    /// Only use for a connection whose certificate exception the user approved.
    pub fn allow_invalid_certs(mut self, allow: bool) -> Self {
        self.allow_invalid_certs = allow;
        self
    }

    pub fn send(self) -> io::Result<Response> {
        let value = self
            .client
            .context
            .call(
                "host.net.http.open",
                json!({
                    "method": self.method,
                    "url": self.url,
                    "headers": self.headers,
                    "bodyBase64": STANDARD.encode(self.body),
                    "bodyReadHandle": self.body_reader.as_ref().map(|reader| reader.http_handle()),
                    "timeoutMs": self.timeout.as_millis().min(86_400_000) as u64,
                    "allowInvalidCerts": self.allow_invalid_certs,
                }),
            )
            .map_err(rpc_to_io)?;
        response_from(self.client, value)
    }

    /// Open a request whose body is streamed chunk by chunk. Core returns a
    /// handle immediately and performs the request on a worker thread, so
    /// plugin-generated bytes (for example `vfs.writeStream` chunks) reach the
    /// network without being buffered in memory.
    ///
    /// `length` is the exact number of bytes that must be written before
    /// [`StreamingBody::finish`]. Streaming bodies cannot be combined with
    /// [`Request::body`] or [`Request::body_reader`].
    pub fn body_stream(self, length: u64) -> io::Result<StreamingBody> {
        if !self.body.is_empty() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "streaming body cannot be combined with an inline body",
            ));
        }
        if self.body_reader.is_some() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "streaming body cannot be combined with body_reader",
            ));
        }
        // A streamed upload has the same long-running semantics as a
        // Core-owned file reader; the declared size is always sent.
        let timeout = self
            .timeout
            .max(Duration::from_secs(3600))
            .as_millis()
            .min(86_400_000) as u64;
        let value = self
            .client
            .context
            .call(
                "host.net.http.open",
                json!({
                    "method": self.method,
                    "url": self.url,
                    "headers": self.headers,
                    "bodyStream": true,
                    "contentLength": length,
                    "timeoutMs": timeout,
                    "allowInvalidCerts": self.allow_invalid_certs,
                }),
            )
            .map_err(rpc_to_io)?;
        let handle = value["handle"]
            .as_str()
            .ok_or_else(|| io::Error::other("missing streaming body handle"))?
            .to_owned();
        Ok(StreamingBody {
            client: self.client,
            handle: Some(handle),
            expected: length,
            written: 0,
            failed: false,
        })
    }
}

fn response_from(client: HttpClient, value: serde_json::Value) -> io::Result<Response> {
    let stream = value["stream"]
        .as_str()
        .ok_or_else(|| io::Error::other("missing response stream"))?
        .to_owned();
    let status = value["status"]
        .as_u64()
        .ok_or_else(|| io::Error::other("missing HTTP status"))? as u16;
    let headers = serde_json::from_value(value["headers"].clone())
        .map_err(|error| io::Error::other(format!("invalid HTTP headers: {error}")))?;
    Ok(Response {
        client,
        stream,
        status,
        headers,
        closed: false,
    })
}

/// A request body produced by the plugin and streamed through Core.
///
/// Chunks are forwarded as they arrive; the whole body is never buffered.
/// [`StreamingBody::finish`] is the only way to obtain the [`Response`].
/// Dropping an unfinished body asks Core to cancel the request; if the plugin
/// session is already gone, Core still fails the upload at its request
/// deadline (the declared `contentLength` is never reached).
pub struct StreamingBody {
    client: HttpClient,
    handle: Option<String>,
    expected: u64,
    written: u64,
    failed: bool,
}

impl StreamingBody {
    /// Number of bytes accepted for the request body so far.
    pub fn written(&self) -> u64 {
        self.written
    }

    /// Declared total size passed to [`Request::body_stream`].
    pub fn expected(&self) -> u64 {
        self.expected
    }

    /// Forward one chunk. Write every chunk as soon as it is available; a
    /// failed write aborts the request and later calls fail immediately.
    pub fn write_chunk(&mut self, bytes: &[u8]) -> io::Result<()> {
        let Some(handle) = self.handle.clone() else {
            return Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "streaming body is already finished",
            ));
        };
        if self.failed {
            return Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "streaming body was aborted by an earlier write error",
            ));
        }
        let length = bytes.len() as u64;
        if self.written + length > self.expected {
            self.cancel();
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                format!(
                    "streaming body exceeds declared length ({} + {} > {})",
                    self.written, length, self.expected
                ),
            ));
        }
        if bytes.is_empty() {
            return Ok(());
        }
        if let Err(error) = self.client.context.call(
            "host.net.http.body",
            json!({"handle": handle, "base64": STANDARD.encode(bytes), "eof": false}),
        ) {
            self.failed = true;
            self.cancel();
            return Err(rpc_to_io(error));
        }
        self.written += length;
        Ok(())
    }

    /// Close the body and wait for the response head. The returned response
    /// is the same type as [`Request::send`].
    pub fn finish(mut self) -> io::Result<Response> {
        let Some(handle) = self.handle.clone() else {
            return Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "streaming body is already finished",
            ));
        };
        if self.failed {
            return Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "streaming body was aborted by an earlier write error",
            ));
        }
        if self.written != self.expected {
            self.cancel();
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                format!(
                    "streaming body is incomplete ({} of {} bytes)",
                    self.written, self.expected
                ),
            ));
        }
        self.client
            .context
            .call(
                "host.net.http.body",
                json!({"handle": handle, "base64": "", "eof": true}),
            )
            .map_err(rpc_to_io)?;
        let value = self
            .client
            .context
            .call("host.net.http.response", json!({"handle": handle}))
            .map_err(rpc_to_io)?;
        // The handle now belongs to the response stream.
        self.handle = None;
        response_from(self.client.clone(), value)
    }

    /// Abort an unfinished body. Best effort: Core drops the request and the
    /// worker fails the streamed body. Idempotent.
    pub fn cancel(&mut self) {
        if let Some(handle) = self.handle.take() {
            if !self.client.context.closed() {
                let _ = self
                    .client
                    .context
                    .call("host.net.http.close", json!({"stream": handle}));
            }
        }
        self.failed = true;
    }
}

impl Drop for StreamingBody {
    fn drop(&mut self) {
        if self.handle.is_some() {
            self.cancel();
        }
    }
}

pub struct Response {
    client: HttpClient,
    stream: String,
    pub status: u16,
    pub headers: BTreeMap<String, String>,
    closed: bool,
}

impl Response {
    pub fn error_for_status(self) -> io::Result<Self> {
        if self.status >= 400 {
            Err(io::Error::other(format!("HTTP {}", self.status)))
        } else {
            Ok(self)
        }
    }

    pub fn bytes(mut self) -> io::Result<Vec<u8>> {
        let mut value = Vec::new();
        (&mut self)
            .take((READ_LIMIT + 1) as u64)
            .read_to_end(&mut value)?;
        if value.len() > READ_LIMIT {
            return Err(io::Error::other(
                "response exceeds read-all limit; use Read for streaming",
            ));
        }
        Ok(value)
    }

    pub fn text(self) -> io::Result<String> {
        String::from_utf8(self.bytes()?).map_err(io::Error::other)
    }

    pub fn json<T: DeserializeOwned>(self) -> io::Result<T> {
        serde_json::from_slice(&self.bytes()?).map_err(io::Error::other)
    }
}

impl Read for Response {
    fn read(&mut self, output: &mut [u8]) -> io::Result<usize> {
        if output.is_empty() || self.closed {
            return Ok(0);
        }
        let size = output.len().min(256 * 1024);
        let value = self
            .client
            .context
            .call(
                "host.net.http.read",
                json!({"stream": self.stream, "size": size}),
            )
            .map_err(rpc_to_io)?;
        let bytes = STANDARD
            .decode(
                value["base64"]
                    .as_str()
                    .ok_or_else(|| io::Error::other("invalid HTTP chunk"))?,
            )
            .map_err(io::Error::other)?;
        if bytes.len() > size {
            return Err(io::Error::other("HTTP chunk exceeds request"));
        }
        output[..bytes.len()].copy_from_slice(&bytes);
        Ok(bytes.len())
    }
}

impl Drop for Response {
    fn drop(&mut self) {
        if !self.closed && !self.client.context.closed() {
            let _ = self
                .client
                .context
                .call("host.net.http.close", json!({"stream": self.stream}));
        }
        self.closed = true;
    }
}
