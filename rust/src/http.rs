//! HTTP convenience API. Core owns connections, redirects and authorization.
use crate::context::{ContextInner, rpc_to_io};
use base64::{Engine, engine::general_purpose::STANDARD};
use serde::Serialize;
use serde_json::json;
use std::{collections::BTreeMap, io, time::Duration};

const READ_LIMIT: usize = 64 * 1024 * 1024;

mod streaming;
pub use streaming::{Response, StreamingBody};

#[derive(Clone)]
pub struct HttpClient {
    context: ContextInner,
}

impl HttpClient {
    pub(crate) fn new(context: ContextInner) -> Self {
        Self { context }
    }

    pub fn request(&self, method: &str, url: &str) -> Request {
        Request {
            client: self.clone(),
            method: method.into(),
            url: url.into(),
            headers: BTreeMap::new(),
            body: Vec::new(),
            body_reader: None,
            timeout: Duration::from_secs(90),
            allow_invalid_certs: false,
        }
    }

    pub fn get(&self, url: &str) -> Request {
        self.request("GET", url)
    }

    pub fn post(&self, url: &str) -> Request {
        self.request("POST", url)
    }

    pub fn put(&self, url: &str) -> Request {
        self.request("PUT", url)
    }

    pub fn delete(&self, url: &str) -> Request {
        self.request("DELETE", url)
    }
}

pub struct Request {
    client: HttpClient,
    method: String,
    url: String,
    headers: BTreeMap<String, String>,
    body: Vec<u8>,
    body_reader: Option<crate::files::FileReader>,
    timeout: Duration,
    allow_invalid_certs: bool,
}

impl Request {
    pub fn header(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.headers.insert(name.into(), value.into());
        self
    }

    pub fn body(mut self, body: impl AsRef<[u8]>) -> Self {
        self.body_reader = None;
        self.body = body.as_ref().to_vec();
        self
    }

    /// Stream a Core-authorized file directly to HTTP, without buffering it
    /// in the plugin or copying its bytes through IPC. Consumes the reader.
    pub fn body_reader(mut self, reader: crate::files::FileReader) -> Self {
        self.body.clear();
        self.body_reader = Some(reader);
        self.timeout = self.timeout.max(Duration::from_secs(3600));
        self
    }

    pub fn json<T: Serialize>(mut self, value: &T) -> io::Result<Self> {
        self.body_reader = None;
        self.body = serde_json::to_vec(value).map_err(io::Error::other)?;
        self.headers
            .insert("content-type".into(), "application/json".into());
        Ok(self)
    }

    pub fn basic_auth(self, username: &str, password: &str) -> Self {
        self.header(
            "authorization",
            format!(
                "Basic {}",
                STANDARD.encode(format!("{username}:{password}"))
            ),
        )
    }

    pub fn bearer_auth(self, token: &str) -> Self {
        self.header("authorization", format!("Bearer {token}"))
    }

    pub fn timeout(mut self, timeout: Duration) -> Self {
        self.timeout = timeout;
        self
    }

    /// Only use for a connection whose certificate exception the user approved.
    pub fn allow_invalid_certs(mut self, allow: bool) -> Self {
        self.allow_invalid_certs = allow;
        self
    }

    pub fn send(self) -> io::Result<Response> {
        let value = self
            .client
            .context
            .call(
                "host.net.http.open",
                json!({
                    "method": self.method,
                    "url": self.url,
                    "headers": self.headers,
                    "bodyBase64": STANDARD.encode(self.body),
                    "bodyReadHandle": self.body_reader.as_ref().map(|reader| reader.http_handle()),
                    "timeoutMs": self.timeout.as_millis().min(86_400_000) as u64,
                    "allowInvalidCerts": self.allow_invalid_certs,
                }),
            )
            .map_err(rpc_to_io)?;
        response_from(self.client, value)
    }

    /// Open a request whose body is streamed chunk by chunk. Core returns a
    /// handle immediately and performs the request on a worker thread, so
    /// plugin-generated bytes (for example `vfs.writeStream` chunks) reach the
    /// network without being buffered in memory.
    ///
    /// `length` is the exact number of bytes that must be written before
    /// [`StreamingBody::finish`]. Streaming bodies cannot be combined with
    /// [`Request::body`] or [`Request::body_reader`].
    pub fn body_stream(self, length: u64) -> io::Result<StreamingBody> {
        if !self.body.is_empty() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "streaming body cannot be combined with an inline body",
            ));
        }
        if self.body_reader.is_some() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "streaming body cannot be combined with body_reader",
            ));
        }
        // A streamed upload has the same long-running semantics as a
        // Core-owned file reader; the declared size is always sent.
        let timeout = self
            .timeout
            .max(Duration::from_secs(3600))
            .as_millis()
            .min(86_400_000) as u64;
        let value = self
            .client
            .context
            .call(
                "host.net.http.open",
                json!({
                    "method": self.method,
                    "url": self.url,
                    "headers": self.headers,
                    "bodyStream": true,
                    "contentLength": length,
                    "timeoutMs": timeout,
                    "allowInvalidCerts": self.allow_invalid_certs,
                }),
            )
            .map_err(rpc_to_io)?;
        let handle = value["handle"]
            .as_str()
            .ok_or_else(|| io::Error::other("missing streaming body handle"))?
            .to_owned();
        Ok(StreamingBody::new(self.client, handle, length))
    }
}

fn response_from(client: HttpClient, value: serde_json::Value) -> io::Result<Response> {
    let stream = value["stream"]
        .as_str()
        .ok_or_else(|| io::Error::other("missing response stream"))?
        .to_owned();
    let status = value["status"]
        .as_u64()
        .ok_or_else(|| io::Error::other("missing HTTP status"))? as u16;
    let headers = serde_json::from_value(value["headers"].clone())
        .map_err(|error| io::Error::other(format!("invalid HTTP headers: {error}")))?;
    Ok(Response::new(client, stream, status, headers))
}
